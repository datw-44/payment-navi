export type PaymentCandidate = {
  カード: string;
  画像URL: string;
  ポイント種類: string;
  条件要約: string;
  条件: string;
  還元率: string;
  注意: string;
  // 特定の日にだけ適用される特典かどうか。省略時はfalse扱い。
  特定日限定?: boolean;
  // 特定日限定がtrueの場合の対象日。「毎月20日・30日」「毎週月曜・土曜」の形式で記載する。
  対象日条件?: string;
  // アフィリエイト用のカード発行リンク（準備中）。
  // 空欄（未設定）の場合は発行ボタン・PR表記を一切表示しない。
  発行リンク?: string;
};

export type StorePayments = {
  店舗: string;
  // 店舗一覧の絞り込み・グループ表示に使うカテゴリ。
  // 「共通（上記以外）」のようにUIに出さないフォールバック店舗は空文字にする。
  カテゴリ: string;
  // レジでポイントカード（アプリ）を提示・利用すると貯まる、その店舗共通のポイント。
  // 各カードを使うことで貯まる「カード会社独自のポイント」（Oki Dokiポイントなど）は含まない。
  共通ポイント: string[];
  候補: PaymentCandidate[];
  // コストコのように使える決済手段が限定されている店舗で、
  // 「そもそも使えない決済手段」を明示するための一覧（省略時はなし扱い）。
  非対応決済?: string[];
};

