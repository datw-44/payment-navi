  候補: PaymentCandidate[];
  // コストコのように使える決済手段が限定されている店舗で、
  // 「そもそも使えない決済手段」を明示するための一覧（省略時はなし扱い）。
  非対応決済?: string[];
  // ランキング下部に表示する解説文（200〜400字程度）。
  // 「候補」のデータと矛盾しないよう、還元率・条件を必ず確認してから書くこと。
  // 見出しは店舗ページ側で「◯◯で一番お得な払い方」の形で自動生成する。
